import { validateOutputPaths } from './storage.js';

export interface GeneratedImportHandle { readonly uri: string; readonly name: string; }
export interface GeneratedImportContent { readonly name: string; readonly text: string; }

export const MAX_PRIMARY_DOCUMENT_BYTES = 4 * 1024 * 1024;
export const MAX_PRIMARY_DOCUMENT_DEPTH = 128;
export const MAX_PRIMARY_DOCUMENT_NODES = 100_000;
export const MAX_PENDING_IMPORT_DOCUMENTS = 16;
export const MAX_PENDING_IMPORT_BYTES = 16 * 1024 * 1024;

/** Applies the same resource limits to opened files and generated imports. */
export function validatePrimaryDocument(text: string): void {
  const bytes = new TextEncoder().encode(text).byteLength;
  if (bytes > MAX_PRIMARY_DOCUMENT_BYTES) throw new Error(`Primary document exceeds the ${MAX_PRIMARY_DOCUMENT_BYTES}-byte limit (received ${bytes} bytes).`);

  let depth = 0;
  let nodes = 0;
  let inString = false;
  let escaped = false;
  let inPrimitive = false;
  const addNode = (): void => {
    nodes += 1;
    if (nodes > MAX_PRIMARY_DOCUMENT_NODES) throw new Error(`Primary document exceeds the ${MAX_PRIMARY_DOCUMENT_NODES}-node structural limit.`);
  };
  for (const character of text) {
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') {
      addNode();
      inString = true;
      inPrimitive = false;
    } else if (character === '{' || character === '[') {
      addNode();
      depth += 1;
      if (depth > MAX_PRIMARY_DOCUMENT_DEPTH) throw new Error(`Primary document exceeds the ${MAX_PRIMARY_DOCUMENT_DEPTH}-level nesting limit.`);
      inPrimitive = false;
    } else if (character === '}' || character === ']') {
      depth = Math.max(0, depth - 1);
      inPrimitive = false;
    } else if (character === ',' || character === ':' || /\s/.test(character)) {
      inPrimitive = false;
    } else if (!inPrimitive) {
      addNode();
      inPrimitive = true;
    }
  }
}

/** Host-owned, validated content. Opaque handles never authorize a renderer-supplied filesystem path. */
export class GeneratedImportRegistry {
  private readonly documents = new Map<string, GeneratedImportContent>();
  private retainedBytes = 0;

  constructor(private readonly maxDocuments = MAX_PENDING_IMPORT_DOCUMENTS, private readonly maxBytes = MAX_PENDING_IMPORT_BYTES) {
    if (!Number.isInteger(maxDocuments) || maxDocuments < 1) throw new Error('Generated import retention limit must be a positive integer.');
    if (!Number.isInteger(maxBytes) || maxBytes < 1) throw new Error('Generated import byte limit must be a positive integer.');
  }

  register(id: string, files: Readonly<Record<string, Uint8Array>>): readonly GeneratedImportHandle[] {
    if (!/^[A-Za-z0-9-]+$/.test(id)) throw new Error('Generated import identity must be a host-issued token.');
    const paths = Object.keys(files);
    validateOutputPaths(paths);
    if (paths.length !== 1 || !paths[0]!.toLowerCase().endsWith('.struct.json')) throw new Error('An import must produce exactly one JSON Structure document.');
    const name = paths[0]!.replace(/^.*[\\/]/, '');
    const uri = 'generated-import:' + id + '/' + encodeURIComponent(name);
    if (this.documents.has(uri)) throw new Error('Generated import identity is already registered.');
    const text = new TextDecoder('utf-8', { fatal: true }).decode(files[paths[0]!]!);
    validatePrimaryDocument(text);
    const bytes = new TextEncoder().encode(text).byteLength;
    if (this.documents.size >= this.maxDocuments || this.retainedBytes + bytes > this.maxBytes) throw new Error('Too many generated imports are waiting to be opened or discarded.');
    this.documents.set(uri, { name, text });
    this.retainedBytes += bytes;
    return [{ uri, name }];
  }

  has(uri: string): boolean { return this.documents.has(uri); }

  read(output: GeneratedImportHandle): GeneratedImportContent {
    const document = this.documents.get(output.uri);
    if (!document || document.name !== output.name) throw new Error('Import output was not generated by this editor session.');
    return { ...document };
  }

  consume(output: GeneratedImportHandle): GeneratedImportContent {
    const document = this.read(output);
    this.release(output.uri);
    return document;
  }

  release(uri: string): void {
    const document = this.documents.get(uri);
    if (!document) return;
    this.retainedBytes -= new TextEncoder().encode(document.text).byteLength;
    this.documents.delete(uri);
  }

  clear(): void {
    this.documents.clear();
    this.retainedBytes = 0;
  }
}
